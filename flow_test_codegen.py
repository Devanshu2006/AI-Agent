

"""Turns verified flows into pytest regression tests -> tests/test_flows.py
 
  * PASS / REVIEW    -> a test that re-runs the journey and asserts no HARD check fails
                        (REVIEW = only soft heuristic checks failed, so the test stays green)
  * confirmed FAIL   -> the same test marked @pytest.mark.bug + xfail(strict=False)
                        (green while the bug exists, XPASS the day it is fixed -
                        same convention as test_bugs.py / test_forms.py)
  * UNVERIFIED / FLAKY / GATED flows are NOT turned into tests.
 
The generated file contains a verbatim copy of flow_engine.py (so it has no
project imports and passes code_validator.py) plus the flows as plain data.
"""
import inspect
import os
import pprint
import re
from pathlib import Path
 
import flow_engine
 
try:
    from bug_detector import USE_XFAIL
except Exception:  # pragma: no cover
    USE_XFAIL = os.getenv("BUG_TESTS_XFAIL", "1") == "1"
 
FLOW_TEST_FILE = Path("generated_tests") / "tests" / "test_flows.py"
 
HEADER = '''# Flow (user-journey) tests - GENERATED by flow_test_codegen.py, do not edit by hand.
# Regenerated on every agent run. The engine below is a verbatim copy of flow_engine.py.
import pytest
 
'''
 
 
def _slug(text):
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")[:40] or "flow"
 
 
def generate_flow_tests(results, path=FLOW_TEST_FILE):
    """Write tests/test_flows.py. Returns the path, or None when nothing to write."""
    if not isinstance(results, dict) or not results.get("flows"):
        print("[Flows] No flow results, so no flow tests were generated.")
        return None
 
    blocks, count = [], 0
    for n, record in enumerate(results["flows"], start=1):
        if record["verdict"] not in ("PASS", "REVIEW", "FAIL"):
            continue
        count += 1
        const = f"FLOW_{n:02d}"
        name = f"test_flow_{n:02d}_{_slug(record['id'])}"
        doc = re.sub(r"\s+", " ", f"{record['name']} - {record['description']}").replace(
            '"', "'").replace("\\", "/")
        decorators = ""
        if record["verdict"] == "FAIL":
            decorators = "@pytest.mark.bug\n"
            if USE_XFAIL:
                decorators += (f"@pytest.mark.xfail(strict=False, "
                               f"reason={('flow bug: ' + record['id'])!r})\n")
        blocks.append(
            f"{const} = {pprint.pformat(record['flow'], width=100, sort_dicts=False)}\n\n\n"
            f"{decorators}def {name}(page):\n"
            f'    """{doc}"""\n'
            f"    result = run_flow(page, {const})\n"
            f'    assert result["verdict"] in ("PASS", "REVIEW"), result["summary"]\n')
 
    if not count:
        print("[Flows] No verified flows, so no flow tests were generated.")
        return None
 
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + inspect.getsource(flow_engine) + "\n\n" + "\n\n".join(blocks),
                    encoding="utf-8")
    print(f"[Flows] Generated {count} flow test(s): {path}")
    return str(path)
 
 
if __name__ == "__main__":
    import json
    import sys
    import flow_tester
    source = Path(sys.argv[1] if len(sys.argv) > 1 else flow_tester.RESULTS_FILE)
    generate_flow_tests(json.loads(source.read_text(encoding="utf-8")))
 
